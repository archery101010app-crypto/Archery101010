import type { BowConfig, UserProfile } from "./authService";

export const OWNER_SELF_SERVICE_PROFILE_KEYS = new Set<string>([
  "fullName",
  "nickname",
  "birthDate",
  "country",
  "city",
  "gender",
  "unitSystem",
  "whatsappNumber",
  "clubName",
  "clubCountry",
  "fcmToken",
  "profileSetupCompleted",
  "bowConfig",
  "bows",
  "physicalData",
  "lastActiveAt",
  "updatedAt"
]);

const NON_COACH_CLUB_IDS = new Set(["CLB-DIRECTOR", "CLB-101010", "CLB-DEMO"]);

function stripUndefinedDeep<T = any>(obj: T): T {
  if (obj === null || obj === undefined) return obj;
  if (Array.isArray(obj)) {
    return obj.map((item) => (item === undefined ? null : stripUndefinedDeep(item))) as unknown as T;
  }
  if (typeof obj === "object" && !(obj instanceof Date)) {
    const cleaned: Record<string, any> = {};
    for (const [k, v] of Object.entries(obj as Record<string, any>)) {
      if (v !== undefined) {
        cleaned[k] = stripUndefinedDeep(v);
      }
    }
    return cleaned as T;
  }
  return obj;
}

export function isSuperAdminEmailPure(email?: string | null): boolean {
  if (!email) return false;
  const clean = email.trim().toLowerCase();
  return (
    clean === "admin101010" ||
    clean === "admin@archery101010.com" ||
    clean === "admin101010@archery101010.com" ||
    clean === "info@archery101010.com" ||
    clean === "archery101010app@gmail.com"
  );
}

export function getCanonicalCoachClubIdPure(coach: Partial<UserProfile> | null | undefined): string {
  if (!coach?.uid) return "CLB-DIRECTOR";
  return "CLB-" + coach.uid.replace("USR-", "");
}

export function getExternalCoachUidPure(user: Partial<UserProfile> | null | undefined): string | null {
  if (!user?.uid) return null;
  if (user.coachId && user.coachId !== user.uid) {
    return user.coachId;
  }
  const ownCanonical = "CLB-" + user.uid.replace("USR-", "");
  if (
    user.clubId &&
    user.clubId.startsWith("CLB-") &&
    user.clubId !== ownCanonical &&
    user.clubId !== `CLB-${user.uid}` &&
    !NON_COACH_CLUB_IDS.has(user.clubId)
  ) {
    const candidateUid = user.clubId.slice(4);
    if (candidateUid && candidateUid !== user.uid) {
      return candidateUid;
    }
  }
  return null;
}

export function isLinkedToExternalCoachPure(user: Partial<UserProfile> | null | undefined): boolean {
  if (!user?.uid) return false;
  if (getExternalCoachUidPure(user) !== null) return true;
  if (user.coachId && user.coachId === user.uid) return false;
  const ownCanonical = "CLB-" + user.uid.replace("USR-", "");
  if (
    user.clubId &&
    user.clubId !== ownCanonical &&
    user.clubId !== `CLB-${user.uid}` &&
    !NON_COACH_CLUB_IDS.has(user.clubId) &&
    !user.isClubCreator
  ) {
    return true;
  }
  return false;
}

export function sanitizeUserProfilePure(u: any): UserProfile {
  const copy = { ...u };
  delete copy.password;
  delete copy.actAsCoach;

  if (copy.uid) {
    if (copy.coachId && copy.coachId === copy.uid) {
      copy.coachId = null;
      copy.coachName = null;
      copy.coachEmail = null;
    }

    if (isLinkedToExternalCoachPure(copy)) {
      copy.isClubCreator = false;
      copy.clubInviteCode = "";
      if (copy.role !== "superadmin" && !isSuperAdminEmailPure(copy.email)) {
        copy.role = "archer";
      }
      const externalCoachUid = getExternalCoachUidPure(copy);
      if (!copy.coachId && externalCoachUid) {
        copy.coachId = externalCoachUid;
      }
      if (copy.clubName === "Club Archery 101010") {
        copy.clubName = null;
      }
    } else if (copy.role === "archer" && !copy.isClubCreator) {
      copy.clubId = null;
      copy.coachId = null;
      copy.coachName = null;
      copy.coachEmail = null;
      copy.clubInviteCode = "";
      copy.joinedWithInviteCode = "";
    } else if (
      copy.role === "coach" ||
      copy.role === "team_admin" ||
      copy.role === "team_admin_coach" ||
      (copy.isClubCreator && copy.role !== "archer")
    ) {
      copy.clubId = getCanonicalCoachClubIdPure(copy);
      copy.isClubCreator = true;
      copy.coachId = null;
      copy.coachName = null;
      copy.coachEmail = null;
    }
  }

  for (const k of Object.keys(copy)) {
    if (copy[k] === undefined) delete copy[k];
  }
  return copy as UserProfile;
}

export function isAutoGeneratedNickname(
  nick?: string | null,
  email?: string | null,
  fullName?: string | null
): boolean {
  const clean = (nick || "").trim().toLowerCase();
  if (!clean || clean === "arquero" || clean === "invitado") return true;
  const emailPrefix = (email || "")
    .split("@")[0]
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "")
    .slice(0, 15);
  const nameSlug = (fullName || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "")
    .slice(0, 15);
  return Boolean((emailPrefix && clean === emailPrefix) || (nameSlug && clean === nameSlug));
}

export function mergeUserProfilesNonDestructive(
  local: UserProfile | null | undefined,
  remote: UserProfile
): { merged: UserProfile; localHadMissingCloudFields: boolean } {
  if (!local || local.uid !== remote.uid) {
    return { merged: sanitizeUserProfilePure(remote), localHadMissingCloudFields: false };
  }

  let localHadMissingCloudFields = false;
  const localTs = Number(local.updatedAt || 0);
  const remoteTs = Number(remote.updatedAt || 0);
  const localIsNewer = localTs > 0 && localTs > remoteTs;

  const pickFieldStr = (remoteVal?: string | null, localVal?: string | null): string => {
    const r = (remoteVal || "").trim();
    const l = (localVal || "").trim();
    if (localIsNewer && l) {
      if (l !== r) localHadMissingCloudFields = true;
      return localVal as string;
    }
    if (r) return remoteVal as string;
    if (l) {
      localHadMissingCloudFields = true;
      return localVal as string;
    }
    return "";
  };

  const refEmail = remote.email || local.email;
  const refFullName = pickFieldStr(remote.fullName, local.fullName);

  const pickNickname = (): string => {
    const r = (remote.nickname || "").trim();
    const l = (local.nickname || "").trim();
    if (localIsNewer && l) {
      if (l !== r) localHadMissingCloudFields = true;
      return local.nickname;
    }
    if (
      l &&
      !isAutoGeneratedNickname(l, refEmail, refFullName) &&
      (!r || isAutoGeneratedNickname(r, refEmail, refFullName))
    ) {
      localHadMissingCloudFields = true;
      return local.nickname;
    }
    if (r) return remote.nickname;
    if (l) {
      localHadMissingCloudFields = true;
      return local.nickname;
    }
    return "";
  };

  const remotePhys = remote.physicalData;
  const localPhys = local.physicalData;
  const rHeight = Number(remotePhys?.height || 0);
  const lHeight = Number(localPhys?.height || 0);
  const height =
    localIsNewer && lHeight > 0
      ? (lHeight !== rHeight && (localHadMissingCloudFields = true), lHeight)
      : rHeight > 0
      ? rHeight
      : lHeight > 0
      ? ((localHadMissingCloudFields = true), lHeight)
      : 0;

  const rWeight = Number(remotePhys?.weight || 0);
  const lWeight = Number(localPhys?.weight || 0);
  const weight =
    localIsNewer && lWeight > 0
      ? (lWeight !== rWeight && (localHadMissingCloudFields = true), lWeight)
      : rWeight > 0
      ? rWeight
      : lWeight > 0
      ? ((localHadMissingCloudFields = true), lWeight)
      : 0;

  const mergedPhysicalData =
    remotePhys || localPhys
      ? {
          height,
          weight,
          dominantEye:
            (localIsNewer ? localPhys?.dominantEye : remotePhys?.dominantEye) ||
            remotePhys?.dominantEye ||
            localPhys?.dominantEye,
          dominantHand:
            (localIsNewer ? localPhys?.dominantHand : remotePhys?.dominantHand) ||
            remotePhys?.dominantHand ||
            localPhys?.dominantHand ||
            "R"
        }
      : undefined;

  const isLegacyPlaceholderBow = (b?: BowConfig | null) =>
    Boolean(
      b &&
        b.type === "Barebow" &&
        !b.brand?.trim() &&
        !b.model?.trim() &&
        Number(b.poundage) === 35 &&
        !b.drawLength
    );

  const hasPopulatedBow = (b?: BowConfig | null) =>
    Boolean(
      b &&
        !isLegacyPlaceholderBow(b) &&
        (b.brand?.trim() || b.model?.trim() || Number(b.poundage) > 0 || Number(b.drawLength) > 0)
    );

  let mergedBows = remote.bows;
  if (localIsNewer && Array.isArray(local.bows) && local.bows.length > 0) {
    if (JSON.stringify(local.bows) !== JSON.stringify(remote.bows)) {
      localHadMissingCloudFields = true;
    }
    mergedBows = local.bows;
  } else if (
    (!Array.isArray(remote.bows) || remote.bows.length === 0) &&
    Array.isArray(local.bows) &&
    local.bows.length > 0
  ) {
    mergedBows = local.bows;
    localHadMissingCloudFields = true;
  }

  let mergedBowConfig = remote.bowConfig;
  if (localIsNewer && hasPopulatedBow(local.bowConfig)) {
    if (JSON.stringify(local.bowConfig) !== JSON.stringify(remote.bowConfig)) {
      localHadMissingCloudFields = true;
    }
    mergedBowConfig = local.bowConfig;
  } else if (!hasPopulatedBow(remote.bowConfig) && hasPopulatedBow(local.bowConfig)) {
    mergedBowConfig = local.bowConfig;
    localHadMissingCloudFields = true;
  }

  const mergedClubName =
    localIsNewer && local.clubName !== undefined
      ? local.clubName
      : remote.clubName || local.clubName || null;

  const merged = sanitizeUserProfilePure({
    ...local,
    ...remote,
    uid: remote.uid,
    fullName: refFullName,
    nickname: pickNickname(),
    birthDate: pickFieldStr(remote.birthDate, local.birthDate),
    country: pickFieldStr(remote.country, local.country),
    city: pickFieldStr(remote.city, local.city),
    gender: pickFieldStr(remote.gender, local.gender),
    whatsappNumber: pickFieldStr(remote.whatsappNumber, local.whatsappNumber),
    clubName: mergedClubName,
    unitSystem:
      (localIsNewer ? local.unitSystem : remote.unitSystem) ||
      remote.unitSystem ||
      local.unitSystem,
    ...(mergedPhysicalData ? { physicalData: mergedPhysicalData } : {}),
    ...(mergedBowConfig ? { bowConfig: mergedBowConfig } : {}),
    ...(mergedBows ? { bows: mergedBows } : {}),
    profileSetupCompleted: Boolean(remote.profileSetupCompleted || local.profileSetupCompleted),
    updatedAt: Math.max(remoteTs, localTs)
  });

  return { merged, localHadMissingCloudFields };
}

export function buildOwnerSelfServiceProfilePatch(source: Partial<UserProfile>): Record<string, any> {
  const patch: Record<string, any> = {};
  for (const [k, v] of Object.entries(source)) {
    if (OWNER_SELF_SERVICE_PROFILE_KEYS.has(k) && v !== undefined) {
      patch[k] = v;
    }
  }
  return stripUndefinedDeep(patch);
}
